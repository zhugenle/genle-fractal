import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash,randomUUID} from 'node:crypto';

export const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const hash=data=>createHash('sha256').update(data).digest('hex');
export function inProject(relative){const p=path.resolve(ROOT,relative);if(!p.startsWith(ROOT+path.sep))throw Error('Path escapes project: '+relative);return p;}
export async function assemble(){
 const config=JSON.parse(await fs.readFile(inProject('config/build.json'),'utf8'));
 const formulaDir=`src/formulas/${config.formula}`;
 const formula=JSON.parse(await fs.readFile(inProject(formulaDir+'/definition.json'),'utf8'));
 if(config.version!==1||formula.id!==config.formula||formula.contract!=='genle-formula-v1'||formula.entryPoint!=='evaluateFormula'||formula.uniformLayout!=='uber-bulb-packed-v1')throw Error('Unsupported formula contract; coordinate an adapter migration first.');
 const outputs=new Map(),inputs=new Map();
 function emit(target,bytes){if(outputs.has(target))throw Error('Duplicate build output: '+target);outputs.set(target,bytes);}
 async function read(relative){relative=relative.replaceAll('{formula}',formulaDir);const data=await fs.readFile(inProject(relative));inputs.set(relative,hash(data));return data;}
 const studioFormulas=[];
 for(const id of config.studioFormulas||[config.formula]){
  const definition=JSON.parse((await read('src/formulas/'+id+'/definition.json')).toString());
  if(definition.id!==id||definition.contract!=='genle-formula-v1'||!['uber-bulb-packed-v1','spiked-cube-packed-v1'].includes(definition.uniformLayout))throw Error('Unsupported studio formula '+id);
  const profile=config.studioDefaults?.[id];
  if(config.studioFormulas&&(!profile||!['yaw','pitch','distance','roll'].every(k=>Number.isFinite(profile.camera?.[k]))))throw Error('Missing studio opening profile for '+id);
  studioFormulas.push(definition);
 }
 async function registry(){
  const chunks=[];
  for(const def of studioFormulas){
   const parts=[];for(const name of ['parameters.js','animation.js','uniforms.js'])parts.push((await read('src/formulas/'+def.id+'/'+name)).toString());
   chunks.push('(()=>{'+parts.join('\n')+'\nreturn {id:'+JSON.stringify(def.id)+',name:'+JSON.stringify(def.name)+',profile:'+JSON.stringify(config.studioDefaults?.[def.id]||{})+',groups:FORMULA_GROUPS,hidden:typeof FORMULA_HIDDEN_PARAMETERS==="undefined"?[]:FORMULA_HIDDEN_PARAMETERS,reference:REFERENCE_FORMULA_PARAMETERS,phases:referencePhases,upload:uploadFormulaUniforms};})()');
  }
  return 'const STUDIO_FORMULAS=['+chunks.join(',\n')+'];\nconst FORMULA_UNIFORMS='+JSON.stringify([...new Set(studioFormulas.flatMap(d=>d.uniforms))])+ ';';
 }
 const header=`'use strict';\nconst $=id=>document.getElementById(id),TAU=Math.PI*2;\nconst FORMULA_UNIFORMS=${JSON.stringify(formula.uniforms)};\n`;
 for(const [target,parts]of Object.entries(config.bundles)){
  const chunks=[];for(const part of parts)chunks.push(`\n/* source: ${part.replaceAll('{formula}',formulaDir)} */\n`+(part==='{studio-formulas}'?await registry(): (await read(part)).toString()));
  emit(target,Buffer.from('// Generated by scripts/build.mjs. Edit src, never this bundle.\n(function(){\n'+(target==='uber.js'?header.replace(/const FORMULA_UNIFORMS=.*;\n/,''):header)+chunks.join('\n')+'\n})();\n'));
 }
 for(const [target,parts]of Object.entries(config.shaders)){
  const chunks=[];for(const part of parts)chunks.push(`\n/* source: ${part.replaceAll('{formula}',formulaDir)} */\n`+(await read(part)).toString());
  emit(target,Buffer.from('// Generated shader: formula + shared renderer + compatibility profile.\n'+chunks.join('\n')));
 }
 for(const [target,source]of Object.entries(config.copies))emit(target,await read(source));
 for(const name of (await fs.readdir(inProject('public'))).sort())emit(name,await read('public/'+name));
 for(const name of (await fs.readdir(inProject('release/pages'))).sort())emit(name,await read('release/pages/'+name));
 inputs.set('config/build.json',hash(await fs.readFile(inProject('config/build.json'))));
 inputs.set('scripts/build.mjs',hash(await fs.readFile(inProject('scripts/build.mjs'))));
 inputs.set(formulaDir+'/definition.json',hash(await fs.readFile(inProject(formulaDir+'/definition.json'))));
 emit('build-manifest.json',Buffer.from(JSON.stringify({schema:'genle-build-v1',formula:formula.id,contract:formula.contract,inputs:Object.fromEntries([...inputs].sort()),outputs:Object.fromEntries([...outputs].map(([name,bytes])=>[name,hash(bytes)]).sort())},null,2)+'\n'));
 return {outputs,config,formula};
}
export async function buildSite({check=false}={}){
 const {outputs,config}=await assemble();
 const outputDir=inProject(config.output);
 await fs.mkdir(outputDir,{recursive:true});
 const mismatch=[];
 for(const [name,bytes]of outputs){
  const target=path.resolve(outputDir,name);if(!target.startsWith(outputDir+path.sep))throw Error('Output escapes dist: '+name);
  if(check){let actual;try{actual=await fs.readFile(target);}catch(_){}if(!actual?.equals(bytes))mismatch.push(name);}
  else{
   let actual;try{actual=await fs.readFile(target);}catch(_){}
   if(actual?.equals(bytes))continue;
   await fs.mkdir(path.dirname(target),{recursive:true});
   const temporary=target+'.'+randomUUID()+'.tmp';
   try{await fs.writeFile(temporary,bytes);await fs.rename(temporary,target);}finally{await fs.rm(temporary,{force:true});}
  }
 }
 // Known obsolete generated scripts only; never recursively delete user files.
 for(const name of config.obsolete||[]){const target=path.resolve(outputDir,name);if(!target.startsWith(outputDir+path.sep))throw Error('Invalid obsolete output');if(check){try{await fs.access(target);mismatch.push(name+' (obsolete)');}catch(_){}}else await fs.rm(target,{force:true});}
 if(mismatch.length)throw Error('dist differs from source: '+mismatch.join(', ')+'. Run npm run build.');
 console.log(check?'Generated output matches source.':`Built ${outputs.size} assets from isolated source modules.`);
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))buildSite({check:process.argv.includes('--check')}).catch(e=>{console.error(e.message);process.exitCode=1;});
