import fs from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=await fs.readFile(new URL('../render-budget.js',import.meta.url),'utf8');
const Budget=vm.runInNewContext(source+';FractalRenderBudget');
const budget=new Budget(null);
const first=budget.dimensions(1000,600,3,true);
for(let i=0;i<3;i++)budget.observe(120,1000+i*1000);
const firstFallback=budget.dimensions(1000,600,3,true);
assert.equal(firstFallback.shaderQuality,2,'Slow frames should first reduce the shader tier');
assert.equal(firstFallback.width,first.width,'The first fallback must preserve raster density');
for(let i=0;i<18;i++)budget.observe(120,4000+i*1000);
const slow=budget.dimensions(1000,600,3,true);
assert(slow.width>=1250&&slow.height>=750,'Slow hardware must preserve a sharp raster floor');
assert.equal(slow.detailHeight,first.detailHeight,'Do not enlarge the normal sampling footprint as raster density changes');
assert.equal(slow.shaderQuality,1,'Adaptive tier should stop at standard for the fine preset');
assert.equal(slow.mappingHeight,first.mappingHeight,'Screen material mapping must not move with the budget');
const paused=budget.dimensions(1000,600,3,false);
assert.equal(paused.width,3000,'Pause/export must retain the selected full resolution');
assert.equal(paused.height,paused.detailHeight);
assert.equal(paused.shaderQuality,3,'Pause/export must restore the chosen shader tier');
for(let i=0;i<90;i++)budget.observe(8,23000+i*1000);
const recovered=budget.dimensions(1000,600,3,true);
assert.equal(recovered.shaderQuality,3,'Sustained headroom must recover the requested tier');
assert(recovered.width>=first.width,'Recover pixel density before restoring expensive shader work');
const draft=budget.dimensions(1000,600,.65,true,0);
assert.equal(draft.shaderQuality,0,'Adaptive must not promote a deliberately selected draft tier');
assert(draft.factor<=.65,'Draft must respect its requested pixel budget');
const huge=budget.dimensions(10000,10000,3,true);
assert(huge.width<=4096&&huge.height<=4096,'Large stages must respect hardware limits');
assert(huge.width*huge.height<=2003000,'Dynamic pixel ceiling must remain bounded after rounding');
budget.observe(NaN,50000);budget.observe(-1,51000);
assert(Number.isFinite(budget.factor),'Invalid timer values must not poison the budget');
console.log('PASS: shader-first fallback, sharp raster floor, stable normals/materials and full-quality export.');
